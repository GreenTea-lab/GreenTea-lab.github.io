let dict = RU;
export let LANG = 'ru';

export function setLang(code) {
  const ruLike = ['ru', 'be', 'kk', 'uk', 'uz', 'ky', 'tg', 'hy', 'az', 'ka'];
  LANG = ruLike.includes(code) ? 'ru' : 'en';
  dict = LANG === 'ru' ? RU : EN;
  document.documentElement.lang = LANG;
  document.title = dict.docTitle;
}

export function t(key, vars) {
  let v = dict[key];
  if (v === undefined) return key;
  if (vars) for (const k in vars) v = v.replace('{' + k + '}', vars[k]);
  return v;
}

// «5 букв», «2 буквы», «1 буква»
export function lettersWord(n) {
  if (LANG !== 'ru') return n === 1 ? dict.letters1 : dict.letters5;
  const m10 = n % 10,
    m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return dict.letters1;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return dict.letters2;
  return dict.letters5;
}

