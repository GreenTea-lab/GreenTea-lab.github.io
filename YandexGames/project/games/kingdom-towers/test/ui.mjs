const out = '/tmp/claude-0/-home-claude/fc31419c-4951-5c39-8720-5e89ab1869b0/scratchpad/td_';
const [name, w, h, mobile, dpr] = [process.argv[2], +process.argv[3], +process.argv[4], process.argv[5] === '1', +(process.argv[6] || 1)];
const shot = (page, n) => page.screenshot({ path: out + name + '_' + n + '.png' });
const errs = await run({ w, h, mobile, dpr, debug: {}, steps: async (page) => {
  const G = (f, a) => page.evaluate(f, a);
  await shot(page, '1menu');
  await G(() => window.__game.scene.getScene('Menu').scene.start('Levels'));
  await page.waitForTimeout(800);
  await shot(page, '2levels');
  await G(() => window.__game.scene.getScene('Levels').scene.start('Shop', { from: 'Levels' }));
  await page.waitForTimeout(800);
  await shot(page, '3shop');
  await G(() => window.__game.scene.getScene('Shop').scene.start('Game', { level: 3 }));
  await page.waitForFunction(() => { const g = window.__game.scene.getScene('Game'); return g.hud && g.hud.ready; });
  await page.waitForTimeout(800);
  await shot(page, '4intro');
  await G(() => { const h = window.__game.scene.getScene('Hud'); h.closeOverlay(); const g = window.__game.scene.getScene('Game'); g.setPause('modal', false); g.gold = 2000;
    const b = [...g.tiles.build]; const pick = [b[3], b[10], b[20], b[30]]; const types = ['archer','cannon','mage','archer'];
    pick.forEach((k, i) => { const [x,y] = k.split(',').map(Number); g.build(types[i], x, y); });
    const t = [...g.towers.values()]; g.upgrade(t[0]); g.upgrade(t[0]); g.upgrade(t[1]);
    g.startWave(); });
  await page.waitForTimeout(600);
  await G(() => { const h = window.__game.scene.getScene('Hud'); if (h.overlay) { h.closeOverlay(); window.__game.scene.getScene('Game').setPause('modal', false); } });
  await G(() => { const g = window.__game.scene.getScene('Game'); for (let i = 0; i < 300; i++) g.step(1/30); });
  await page.waitForTimeout(700);
  await shot(page, '5battle');
  await G(() => { const g = window.__game.scene.getScene('Game'); const k = [...g.tiles.build].find(k => !g.towers.has(k)); const [x,y] = k.split(',').map(Number); g.hud.showBuildMenu(x, y, 'cannon'); g.showRange('cannon', 1, x, y); });
  await page.waitForTimeout(500);
  await shot(page, '6buildmenu');
  await G(() => { const g = window.__game.scene.getScene('Game'); g.closeMenus(); const t = [...g.towers.values()][0]; g.showRange(t.type, t.lvl, t.cx, t.cy); g.hud.showTowerMenu(t); });
  await page.waitForTimeout(400);
  await shot(page, '7towermenu');
  await G(() => { const g = window.__game.scene.getScene('Game'); g.closeMenus(); g.lives = 17; g.onVictory(); });
  await page.waitForTimeout(2500);
  await shot(page, '8victory');
}});
