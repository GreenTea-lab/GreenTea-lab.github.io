let D = RU;
export let LANG = 'ru';
export function setLang(l) {
  LANG = ['ru', 'be', 'kk', 'uk', 'uz', 'ky', 'tg', 'hy', 'az', 'ka'].includes(l) ? 'ru' : 'en';
  D = LANG === 'ru' ? RU : EN;
  document.documentElement.lang = LANG;
}
export function t(k, vars) {
  let s = D[k] ?? RU[k] ?? k;
  if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, b);
  return s;
}
export const fmt = (n) => Math.floor(n).toLocaleString(LANG === 'ru' ? 'ru-RU' : 'en-US');
export const _dicts = { RU, EN };
