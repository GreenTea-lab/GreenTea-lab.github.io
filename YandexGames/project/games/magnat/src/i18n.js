export let LANG = 'ru';
export function setLang(l) {
  LANG = ['ru', 'be', 'kk', 'uk', 'uz', 'ky', 'tg', 'hy', 'az', 'ka'].includes(l) ? 'ru' : 'en';
  D = LANG === 'ru' ? RU : EN;
  document.documentElement.lang = LANG;
  document.title = D.title;
}
export function t(k, vars) {
  let s = D[k] ?? RU[k] ?? k;
  if (vars && typeof s === 'string') for (const [a, b] of Object.entries(vars)) s = s.split(`{${a}}`).join(b);
  return s;
}
export const fmt = (n) => Math.floor(n).toLocaleString(LANG === 'ru' ? 'ru-RU' : 'en-US');
// деньги партии: 1 единица = 1 000 ₽
export function money(n) {
  const v = Math.round(n * 1000);
  return LANG === 'ru' ? `${v.toLocaleString('ru-RU')} ₽` : `₽${v.toLocaleString('en-US')}`;
}
// коротко: 1,52 млн ₽ / 850 тыс. ₽
export function moneyS(n) {
  const neg = n < 0 ? '-' : '';
  n = Math.abs(n);
  if (LANG === 'ru') {
    if (n >= 1000) return `${neg}${(n / 1000).toLocaleString('ru-RU', { maximumFractionDigits: n >= 10000 ? 1 : 2 })} млн ₽`;
    return `${neg}${Math.round(n)} тыс. ₽`;
  }
  if (n >= 1000) return `${neg}₽${(n / 1000).toLocaleString('en-US', { maximumFractionDigits: n >= 10000 ? 1 : 2 })}M`;
  return `${neg}₽${Math.round(n)}K`;
}
