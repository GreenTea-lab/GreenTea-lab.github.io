import fs from 'node:fs';import crypto from 'node:crypto';
import {level,COUNT} from '../src/levels.js';
import {legacyLevel} from '../src/legacy-levels.js';
import {Game} from '../src/core.js';
import {auditDeal} from './balance-model.mjs';

fs.mkdirSync('test-results/balance',{recursive:true});
const rows=[],catalog=[],failures=[];let attempts=0;
for(let i=0;i<COUNT;i++){
  const L=level(i),early=i<50;
  const range=L.tier==='easy'?[1,1]:L.tier==='normal'?(early?[.75,.95]:[.6,.88]):(early?[.3,.65]:[.15,.56]);
  const midpoint=(range[0]+range[1])/2,candidates=[];
  for(let n=0;n<(L.tier==='easy'?3:100);n++){
    const seed=(950003+i*104729+n*15485863)>>>0;
    const g=new Game({...L,seed});attempts++;
    const scout=auditDeal(g,L.tier==='easy'?12:24,731003+i*13);
    if(L.tier!=='easy'&&(scout.clearRate<range[0]-.09||scout.clearRate>range[1]+.09))continue;
    const audit=auditDeal(g,L.tier==='easy'?12:96,171339+i*101+n*29);
    const distance=Math.max(0,range[0]-audit.clearRate,audit.clearRate-range[1]);
    candidates.push({seed,...audit,distance,score:distance*10+Math.abs(audit.clearRate-midpoint)});
    if(candidates.filter(c=>c.distance===0).length>=3)break;
  }
  candidates.sort((a,b)=>a.score-b.score);
  if(candidates.length<3)throw Error('Not enough candidate deals for level '+(i+1));
  const chosen=candidates.slice(0,3);
  if(chosen.some(c=>c.distance>0))failures.push({level:i+1,tier:L.tier,target:range,rates:chosen.map(c=>c.clearRate)});
  catalog.push([chosen.map(c=>c.seed),chosen.map(c=>Math.round(c.clearRate*1000)/1000)]);
  rows.push({level:i+1,city:L.city,tier:L.tier,lay:L.lay,pairs:L.pairs,layers:1+Math.max(...L.pos.map(p=>p.z)),pairCopies:L.pairCopies,locks:L.locks,hiddenCount:L.hiddenCount,par:L.par,target:range,deals:chosen});
  if((i+1)%50===0)console.log('Audited',i+1,'levels;',attempts,'candidates;',failures.length,'outliers');
}
const config=Array.from({length:COUNT},(_,i)=>{const L=level(i);return {pos:L.pos,types:L.types,pairCopies:L.pairCopies,locks:L.locks,hiddenCount:L.hiddenCount};});
const hash=crypto.createHash('sha256').update(JSON.stringify(config)).digest('hex');
fs.writeFileSync('src/campaign-seeds.js','// Generated by tools/balance-campaign.mjs. Clear rates are blind-play proxies, not player win rates.\nexport const CAMPAIGN_CONFIG_HASH='+JSON.stringify(hash)+';\nexport const CAMPAIGN_SEEDS='+JSON.stringify(catalog)+';\n');
const earlyBaseline=[];
for(let i=0;i<50;i++){const L=legacyLevel(i);earlyBaseline.push({level:i+1,pairs:L.pairs,...auditDeal(new Game({...L,seed:103}),64,70001+i)});}
fs.writeFileSync('test-results/balance/calibration.json',JSON.stringify({date:new Date().toISOString(),configHash:hash,method:'Uniform legal-pair choices; deterministic simulations, not human win rates',attempts,failures,earlyBaseline,rows},null,2));
console.log('Calibration complete:',rows.length,'levels,',failures.length,'outliers');
if(failures.length)console.log(JSON.stringify(failures));
