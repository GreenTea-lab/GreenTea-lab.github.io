// развернуть раскладку в список позиций {x, y, z}
export function positions(name) {
  const L = LAYOUTS[name];
  const out = [];
  L.forEach((layer, li) => {
    const z = layer.z ?? li;
    layer.r.forEach((row, ry) => {
      let shift = 0;
      if (row[0] === '>') {
        shift = 1;
        row = row.slice(1);
      }
      [...row].forEach((ch, c) => {
        if (ch === '#') out.push({ x: layer.ox + c * 2 + shift, y: layer.oy + ry * 2, z });
      });
    });
  });
  return out;
}
