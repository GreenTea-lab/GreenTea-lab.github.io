let dict = RU;
export let LANG = 'ru';
export function setLang(code) {
  const ruLike = ['ru', 'be', 'kk', 'uk', 'uz', 'ky', 'tg', 'hy', 'az', 'ka'];
  LANG = ruLike.includes(code) ? 'ru' : 'en';
  dict = LANG === 'ru' ? RU : EN;
  document.documentElement.lang = LANG;
  document.title = dict.title;
}
export function t(key, vars) {
  let v = dict[key];
  if (v === undefined) return key;
  if (vars) for (const k in vars) v = v.split('{' + k + '}').join(vars[k]);
  return v;
}

// 1234567 -> «1,23M»
export function fmt(n) {
  n = Math.floor(n);
  const units = LANG === 'ru' ? ['', 'K', 'M', 'B', 'T', 'Qa', 'Qi'] : ['', 'K', 'M', 'B', 'T', 'Qa', 'Qi'];
  if (n < 10000) return String(n);
  let i = 0;
  let v = n;
  while (v >= 1000 && i < units.length - 1) {
    v /= 1000;
    i++;
  }
  const s = v >= 100 ? v.toFixed(0) : v >= 10 ? v.toFixed(1) : v.toFixed(2);
  return (LANG === 'ru' ? s.replace('.', ',') : s) + units[i];
}
export function fmtRate(n) {
  if (n < 10) return (Math.round(n * 10) / 10).toString().replace('.', LANG === 'ru' ? ',' : '.');
  return fmt(n);
}
export function fmtTime(sec) {
  sec = Math.max(0, Math.ceil(sec));
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  const s = sec % 60;
  if (h) return `${h}${t('hours')} ${m}${t('minutes')}`;
  if (m) return `${m}:${String(s).padStart(2, '0')}`;
  return `${s}${t('seconds')}`;
}
