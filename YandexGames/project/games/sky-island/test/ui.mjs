import { run, done } from './shot.mjs';
const out = '/tmp/claude-0/-home-claude/fc31419c-4951-5c39-8720-5e89ab1869b0/scratchpad/si_';
const [name, w, h, mobile, dpr] = [process.argv[2], +process.argv[3], +process.argv[4], process.argv[5] === '1', +(process.argv[6] || 1)];
const shot = (page, n) => page.screenshot({ path: out + name + '_' + n + '.png' });
const errs = await run({ w, h, mobile, dpr, debug: {}, steps: async (page) => {
  const G = (f, a) => page.evaluate(f, a);
  await page.waitForTimeout(1500);
  await shot(page, '1start');
  await G(() => document.querySelector('.bottom .big').click());
  await page.waitForTimeout(1200);
  await shot(page, '2drawer');
  await G(() => { const g = window.__game; g.ui.toggleDrawer(false); g.startPlace('b', 'sawmill'); });
  await page.waitForTimeout(500);
  await shot(page, '3place');
  await G(() => window.__game.confirmPlace());
  await page.waitForTimeout(600);
  await G(() => { const g = window.__game; g.select(g.s.buildings.find(b => b.type === 'farm')); });
  await page.waitForTimeout(600);
  await shot(page, '4sheet');
  await G(() => { const g = window.__game; g.s.coins += 5000; g.upgrade(g.s.buildings.find(b => b.type === 'farm')); });
  await page.waitForTimeout(800);
  await shot(page, '5building');
  await G(() => { const g = window.__game; g.deselect(); g.ui.tasksModal(); });
  await page.waitForTimeout(500);
  await shot(page, '6tasks');
  await G(() => { const g = window.__game; g.ui.closeModal(); g.ui.offlineModal(3700, { coins: 1234, wood: 56 }); });
  await page.waitForTimeout(500);
  await shot(page, '7offline');
  await G(() => { const g = window.__game; g.ui.closeModal(); g.world.spawnBalloon(); g.catchBalloon(); });
  await page.waitForTimeout(500);
  await shot(page, '8chest');
  console.log(await G(() => JSON.stringify({ b: window.__game.s.buildings.map(b => b.type + b.lvl), coins: Math.round(window.__game.s.coins), lvl: window.__game.s.level })));
}});
done(errs);
