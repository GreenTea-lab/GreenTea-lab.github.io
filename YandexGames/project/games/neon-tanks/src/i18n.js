let dict = RU;
export let LANG = 'ru';

export function setLang(code) {
  const ruLike = ['ru', 'be', 'kk', 'uk', 'uz', 'ky', 'tg', 'hy', 'az', 'ka'];
  LANG = ruLike.includes(code) ? 'ru' : 'en';
  dict = LANG === 'ru' ? RU : EN;
  document.documentElement.lang = LANG;
}

export function t(key) {
  const v = dict[key];
  return v === undefined ? key : v;
}

export function tankName(id) {
  const n = TN[id];
  return n ? n[LANG === 'ru' ? 0 : 1] : id;
}

