let dict = RU;
export let LANG = 'ru';

export function setLang(code) {
  const ruLike = ['ru', 'be', 'kk', 'uk', 'uz', 'ky', 'tg', 'hy', 'az', 'ka'];
  LANG = ruLike.includes(code) ? 'ru' : 'en';
  dict = LANG === 'ru' ? RU : EN;
  document.documentElement.lang = LANG;
  document.title = dict.docTitle;
}

export function t(key, vars) {
  let v = dict[key];
  if (v === undefined) return key;
  if (vars) for (const k in vars) v = v.split('{' + k + '}').join(vars[k]);
  return v;
}

export const fishName = (id) => NAMES[LANG][id] || id;

export const fmtNum = (n) => String(Math.floor(n)).replace(/\B(?=(\d{3})+(?!\d))/g, LANG === 'ru' ? ' ' : ',');

// вес: до килограмма — в граммах
export function fmtW(kg) {
  if (kg < 1) return t('g', { n: Math.max(1, Math.round(kg * 1000)) });
  const v = kg < 10 ? kg.toFixed(2) : kg < 100 ? kg.toFixed(1) : Math.round(kg).toString();
  return t('kg', { n: LANG === 'ru' ? v.replace('.', ',') : v });
}

export function fmtTime(sec) {
  sec = Math.max(0, Math.ceil(sec));
  const h = Math.floor(sec / 3600),
    m = Math.floor((sec % 3600) / 60),
    s = sec % 60;
  if (h) return `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
  return `${m}:${String(s).padStart(2, '0')}`;
}
