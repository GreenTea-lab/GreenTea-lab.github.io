let dict = RU;
export let LANG = 'ru';

export function setLang(code) {
  const ruLike = ['ru', 'be', 'kk', 'uk', 'uz', 'ky', 'tg', 'hy', 'az', 'ka'];
  LANG = ruLike.includes(code) ? 'ru' : 'en';
  dict = LANG === 'ru' ? RU : EN;
  document.documentElement.lang = LANG;
  document.title = dict.docTitle;
}

export function t(key, vars) {
  let v = dict[key];
  if (v === undefined) return key;
  if (vars) for (const k in vars) v = v.split('{' + k + '}').join(vars[k]);
  return v;
}

const SUF = {
  ru: ['', ' тыс', ' млн', ' млрд', ' трлн', ' квдр', ' квнт', ' скст', ' сптл', ' октл', ' нонл', ' дцл'],
  en: ['', 'K', 'M', 'B', 'T', 'Qa', 'Qi', 'Sx', 'Sp', 'Oc', 'No', 'Dc'],
};
// большие числа: 1 234 → «1,23 тыс» / «1.23K»
export function fmt(n) {
  if (!isFinite(n)) return '∞';
  n = Math.max(0, n);
  if (n < 1000) return n < 10 && n % 1 ? (LANG === 'ru' ? n.toFixed(1).replace('.', ',') : n.toFixed(1)) : String(Math.floor(n));
  const e = Math.floor(Math.log10(n) / 3);
  const S = SUF[LANG];
  if (e >= S.length) {
    const s = n.toExponential(2);
    return LANG === 'ru' ? s.replace('.', ',') : s;
  }
  const v = n / Math.pow(1000, e);
  let s = v < 10 ? v.toFixed(2) : v < 100 ? v.toFixed(1) : Math.floor(v).toString();
  if (LANG === 'ru') s = s.replace('.', ',');
  return s + S[e];
}
export const fmtInt = (n) => String(Math.floor(n)).replace(/\B(?=(\d{3})+(?!\d))/g, LANG === 'ru' ? ' ' : ',');
export function fmtTime(sec) {
  sec = Math.max(0, Math.ceil(sec));
  const h = Math.floor(sec / 3600),
    m = Math.floor((sec % 3600) / 60),
    s = sec % 60;
  if (h) return `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
  return `${m}:${String(s).padStart(2, '0')}`;
}
