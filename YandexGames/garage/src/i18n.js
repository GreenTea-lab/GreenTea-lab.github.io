let dict = RU;
export let LANG = 'ru';
export function setLang(code) {
  const ruLike = ['ru', 'be', 'kk', 'uk', 'uz', 'ky', 'tg', 'hy', 'az', 'ka'];
  LANG = ruLike.includes(code) ? 'ru' : 'en';
  dict = LANG === 'ru' ? RU : EN;
  document.documentElement.lang = LANG;
  document.title = dict.docTitle;
}
export function t(key, vars) {
  let v = dict[key];
  if (v === undefined) return key;
  if (vars) for (const k in vars) v = v.split('{' + k + '}').join(vars[k]);
  return v;
}
// случайная реплика из списка (seed — для повторяемости)
export function tr(key, vars, seed = Math.random() * 1e6) {
  const arr = dict[key];
  if (!Array.isArray(arr)) return t(key, vars);
  let v = arr[Math.floor(seed) % arr.length];
  if (vars) for (const k in vars) v = v.split('{' + k + '}').join(vars[k]);
  return v;
}
